  // Animated Number Counter on Viewport Entry
  window.initCounters = function () {
    const observer = new IntersectionObserver((entries) => {
      entries.forEach(entry => {
        if (entry.isIntersecting) {
          const el = entry.target;
          const targetText = el.getAttribute('data-target') || el.innerText;
          const match = targetText.match(/^([^\d]*)(\d+)(.*)$/);
          if (match) {
            const prefix = match[1] || '';
            const endVal = parseInt(match[2], 10);
            const suffix = match[3] || '';
            let current = 0;
            const duration = 1200;
            const step = Math.max(1, Math.floor(endVal / (duration / 25)));

            const timer = setInterval(() => {
              current += step;
              if (current >= endVal) {
                current = endVal;
                clearInterval(timer);
              }
              el.innerText = `${prefix}${current.toLocaleString()}${suffix}`;
            }, 25);
          }
          observer.unobserve(el);
        }
      });
    }, { threshold: 0.2 });

    document.querySelectorAll('.count-up').forEach(el => observer.observe(el));
  };
